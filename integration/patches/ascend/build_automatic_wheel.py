"""Assemble FlagTree's real wheel with a separately built Ascend late plugin.

Run only in the matching Ascend build Docker. This deliberately reuses a supplied
matching native build; it does not claim to rebuild the native compiler. Apply
the complete flagtree-source-census-v2.patch to --flagtree and
flir-source-census-v2.patch to its pinned third_party/flir first.
Build --plugin from this component's Profiler/llvm using upstream LLVM15 CMake.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import runpy
import shlex
import shutil
import subprocess
import sys
import zipfile


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--flagtree', type=Path, required=True)
    parser.add_argument('--component', type=Path, required=True)
    parser.add_argument('--native-python', type=Path, required=True)
    parser.add_argument('--core-library', type=Path, required=True)
    parser.add_argument('--plugin', type=Path, required=True)
    parser.add_argument(
        '--actor-structure-tool',
        type=Path,
        help='Matching flagprism-ascend-structure LLVM15 reader')
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    for name in vars(args):
        if getattr(args, name) is not None:
            setattr(args, name, getattr(args, name).resolve())
    compiler_source = (args.flagtree /
                       'third_party/ascend/backend/compiler.py').read_text()
    identity_source = (
        args.flagtree /
        'third_party/ascend/backend/compiler_identity.py').read_text()
    if ('compiler_driver_identity' not in compiler_source
            or 'def file_identity(' not in identity_source):
        raise ValueError(
            'Apply the current census-v2 parent patch with pre-JIT driver identity before assembly'
        )
    args.output.mkdir(parents=True, exist_ok=False)
    integrated = args.flagtree / 'third_party/FlagPrism'
    if not integrated.exists():
        integrated.symlink_to(args.component, target_is_directory=True)
    if not (integrated / 'python/flagprism_build.py').is_file():
        raise ValueError(
            'Component source must include python/flagprism_build.py')
    os.chdir(args.flagtree)
    sys.path.insert(0, str(args.flagtree))
    os.environ.update(TRITON_BUILD_FLAGPRISM='ON',
                      TRITON_BUILD_PROTON='OFF',
                      FLAGPRISM_SOURCE_DIR=str(args.component),
                      TRITON_OFFLINE_BUILD='ON',
                      FLAGTREE_BACKEND='ascend',
                      TORCH_DEVICE_BACKEND_AUTOLOAD='0',
                      USE_FLAGCX='OFF',
                      USE_FLIR='OFF',
                      USE_FLAGPRISM='OFF')
    import setuptools
    from setuptools import Distribution
    from setuptools.command.build_py import build_py
    original_popen = subprocess.Popen

    def no_rebuild(command, *positional, **kwargs):
        words = shlex.split(command) if isinstance(command,
                                                   str) else list(command)
        if kwargs.get('shell') or (words and Path(str(
                words[0])).name in {'bash', 'sh', 'zsh'}) or any(
                    Path(str(word)).name in {'cmake', 'ninja', 'make'}
                    for word in words):
            raise RuntimeError(
                'Wheel assembly must not configure/build a different native library'
            )
        return original_popen(command, *positional, **kwargs)

    subprocess.Popen = no_rebuild

    def no_shell_build(command):
        raise RuntimeError('Wheel assembly must not run an os.system build')

    os.system = no_shell_build
    captured = {}
    original_setup = setuptools.setup
    setuptools.setup = lambda **kwargs: captured.update(kwargs)
    old_argv = sys.argv
    sys.argv = [str(args.flagtree / 'setup.py'), 'bdist_wheel']
    try:
        runpy.run_path(str(args.flagtree / 'setup.py'), run_name='__main__')
    finally:
        setuptools.setup = original_setup
        sys.argv = old_argv
    stage = args.output / 'stage'
    stage.mkdir()
    dist = Distribution(captured)
    dist.script_name = 'setup.py'
    build = dist.get_command_obj('build')
    build.build_base = str(args.output / 'build')
    build.build_lib = str(stage)
    build.ensure_finalized()
    egg_dir = args.output / 'egg'
    egg_dir.mkdir()
    egg = dist.get_command_obj('egg_info')
    egg.egg_base = str(egg_dir)
    egg.ensure_finalized()
    egg.run()
    copier = build_py(dist)
    copier.build_lib = str(stage)
    copier.ensure_finalized()
    copier.run()
    # Match the backend marker generated by the normal CMakeBuildPy command.
    # Standard build_py alone does not generate this non-Python package data.
    from python.setup_tools import setup_helper
    setup_helper.write_flagtree_backend_file(stage / 'triton')
    for component in ('debugger', 'profiler'):
        target = stage / 'flagtree' / component
        target.mkdir(parents=True, exist_ok=True)
        for native in (args.native_python / 'flagtree' / component).iterdir():
            if native.suffix in ('.so', '.h'):
                shutil.copy2(native, target / native.name)
    # Header bytes are part of the generated launcher's cache identity. Always
    # package this source snapshot's canonical ABI header, even with reused
    # matching runtime libraries.
    shutil.copy2(
        args.component /
        'Profiler/csrc/include/Profiler/Vendor/CannLaunchReceipt.h',
        stage / 'flagtree/profiler/_cann_launch_receipt.h')
    core_target = stage / 'triton/_C'
    core_target.mkdir(parents=True, exist_ok=True)
    shutil.copy2(args.core_library, core_target / 'libtriton.so')
    # Existing documented standalone frontend tool is a matching compiler build
    # artifact too; package it rather than relying on the developer checkout.
    tools = args.core_library.parent / 'third_party/ascend/bin'
    for name in ('triton-mlir-opt', ):
        if (tools / name).is_file():
            shutil.copy2(tools / name, core_target / name)
    plugin_target = stage / 'flagtree/profiler/lib'
    plugin_target.mkdir()
    shutil.copy2(args.plugin, plugin_target / args.plugin.name)
    structure_tool = args.actor_structure_tool
    if structure_tool is None:
        sibling = args.plugin.parent / 'flagprism-ascend-structure'
        structure_tool = sibling if sibling.is_file() else None
    if structure_tool is not None:
        shutil.copy2(structure_tool,
                     plugin_target / 'flagprism-ascend-structure')
    wheel = dist.get_command_obj('bdist_wheel')
    wheel.skip_build = True
    wheel.dist_dir = str(args.output / 'dist')
    wheel.bdist_dir = str(args.output / 'bdist')
    wheel.ensure_finalized()
    wheel.run()
    paths = list((args.output / 'dist').glob('*.whl'))
    assert len(paths) == 1, paths
    files = {}
    with zipfile.ZipFile(paths[0]) as archive:
        for path in list(stage.rglob('*.so')) + list(stage.rglob('*.h')) + [
                stage / 'triton/backends/ascend/compiler.py', stage /
                'flagtree/__init__.py', stage / 'triton/FLAGTREE_BACKEND'
        ]:
            relative = path.relative_to(stage).as_posix()
            assert archive.read(relative) == path.read_bytes(), relative
            files[relative] = hashlib.sha256(path.read_bytes()).hexdigest()
        # Both public and Ascend-dispatched JIT paths are executed at runtime.
        # Compare against intended source, not merely a self-consistent stage.
        parent_python = {
            'triton/runtime/jit.py': 'python/triton/runtime/jit.py',
            'triton/spec/ascend/runtime/jit.py':
            'python/triton/spec/ascend/runtime/jit.py',
            'triton/backends/ascend/compiler.py':
            'third_party/ascend/backend/compiler.py',
            'triton/backends/ascend/compiler_identity.py':
            'third_party/ascend/backend/compiler_identity.py',
            'triton/backends/ascend/driver.py':
            'third_party/ascend/backend/driver.py',
            'triton/backends/ascend/utils.py':
            'third_party/ascend/backend/utils.py',
            'flagtree/_flagprism.py': 'python/flagtree/_flagprism.py',
        }
        parent_python_sha256 = {}
        for entry, relative in parent_python.items():
            data = (args.flagtree / relative).read_bytes()
            assert (stage / entry).read_bytes() == data, entry
            assert archive.read(entry) == data, entry
            parent_python_sha256[entry] = hashlib.sha256(data).hexdigest()
        python_count = 0
        component_python_sha256 = {}
        for component in ('Profiler', 'Debugger'):
            source = args.component / component / 'python' / (
                'flagtree_' + component.lower())
            for path in source.rglob('*.py'):
                if '__pycache__' in path.parts:
                    continue
                entry = 'flagtree/' + component.lower(
                ) + '/' + path.relative_to(source).as_posix()
                assert archive.read(entry) == path.read_bytes(), entry
                component_python_sha256[entry] = hashlib.sha256(
                    path.read_bytes()).hexdigest()
                python_count += 1
        plugin_entry = 'flagtree/profiler/lib/' + args.plugin.name
        assert archive.read(plugin_entry) == args.plugin.read_bytes()
        if structure_tool is not None:
            entry = 'flagtree/profiler/lib/flagprism-ascend-structure'
            if archive.read(entry) != structure_tool.read_bytes():
                raise ValueError('Packaged actor structure reader differs')
            files[entry] = hashlib.sha256(
                structure_tool.read_bytes()).hexdigest()
    result = {
        'wheel':
        str(paths[0]),
        'wheel_sha256':
        hashlib.sha256(paths[0].read_bytes()).hexdigest(),
        'files':
        files,
        'component_python_files_verified':
        python_count,
        'component_python_sha256':
        component_python_sha256,
        'parent_python_sha256':
        parent_python_sha256,
        'component_source_snapshot_sha256':
        hashlib.sha256(
            json.dumps(component_python_sha256,
                       sort_keys=True).encode()).hexdigest(),
        'flagtree_commit':
        subprocess.check_output(['git', 'rev-parse', 'HEAD'],
                                cwd=args.flagtree,
                                text=True).strip(),
        'flagtree_tracked_diff_sha256':
        hashlib.sha256(
            subprocess.check_output(['git', 'diff', '--binary'],
                                    cwd=args.flagtree)).hexdigest(),
        'plugin_sources': {
            name:
            hashlib.sha256((args.component / 'Profiler/llvm' /
                            name).read_bytes()).hexdigest()
            for name in ('AscendLateObserver.cpp', 'AscendSourceCensus.h',
                         'AscendTimeline.h', 'CMakeLists.txt')
        },
        'native_provenance':
        'packaging copies supplied artifacts without compiling; see their external native build/source audit',
        'plugin':
        str(args.plugin),
        'plugin_source':
        str(args.component / 'Profiler/llvm'),
        'flagtree':
        str(args.flagtree),
        'component':
        str(args.component)
    }
    (args.output /
     'result.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
